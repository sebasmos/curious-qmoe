"""One summary.md over every analyzed dataset: the static front per
condition, the best primary cascade point at each budget with front.py's
verdict, the humility curve (escalation rate against SNR under thresholds set
on clean inner validation) and calibration.

    python scripts/redesign/idea5/summary_stage2.py ANALYSIS --datasets esc50 urban esc5 --out ANALYSIS/summary.md
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from report_stage2 import cond_key, cond_label, md  # noqa: E402

KEY_CONFIGS = ["fp32", "w8", "w6", "w5", "w4g128", "n4g128", "w4", "n4", "w3g64", "n3g64"]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("analysis", type=Path)
    ap.add_argument("--datasets", nargs="+", required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    parts = ["# Idea 5 Stage 2 summary", "",
             "Generated by scripts/redesign/idea5/summary_stage2.py. The verdict and the corrections from the "
             "independent Stage 3 audit (time-sharing baseline, group-scale pricing, k + 1 bit-planes, tie rule, "
             "multiplicity, fold-level tests) are in the results folder's README.md.", ""]
    for ds in args.datasets:
        adir = args.analysis / ds
        if not (adir / "static.csv").exists():
            continue
        S = pd.read_csv(adir / "static.csv", low_memory=False)
        S = S[S["head"].astype(str) == "esc"]
        conds = sorted(S["condition"].unique(), key=cond_key)
        n_pairs = S.groupby(["condition", "config"]).size().max()
        parts += [f"## {ds} ({n_pairs} (seed, fold) pairs)", "", "### Static systems, FP32 head: macro F1", ""]
        f1 = S.groupby(["config", "condition"])["f1"].mean().unstack()
        f1 = f1.reindex([c for c in KEY_CONFIGS if c in f1.index])[conds]
        bops = S.groupby("config")["bitops"].mean().reindex(f1.index) / 1e12
        f1.columns = [cond_label(c) for c in f1.columns]
        f1.insert(0, "bit-ops (T)", bops)
        parts += [md(f1.reset_index()), ""]
        comp = pd.read_csv(adir / "front_comparisons.csv") if (adir / "front_comparisons.csv").exists() else None
        C = pd.read_csv(adir / "cascades.csv", low_memory=False)
        C = C[(C["head"].astype(str) == "esc") & (C["signal"] == "margin")]
        rate = C.groupby(["condition", "cheap", "expensive", "point"])["rate"].mean()
        if comp is not None and len(comp):
            prim = comp[comp["family"] == "primary"].copy()
            prim["cheap"] = prim["method"].str.split(">").str[0]
            rows = []
            for cond in conds:
                for pt in ["b05", "b10", "b20", "b30", "match"]:
                    g = prim[(prim["condition"] == cond) & (prim["operating_point"] == pt)]
                    if not len(g):
                        continue
                    b = g.sort_values("mean_diff", ascending=False).iloc[0]
                    exp = b["method"].split(">")[1].split("+")[0]
                    rows.append({"condition": cond_label(cond), "point": pt, "best cascade": f"{b['cheap']}>{exp}",
                                 "escalated": rate.get((cond, b["cheap"], exp, pt), float("nan")),
                                 "F1": b["f1_macro"], "bit-ops (T)": b["bitops_per_clip"] / 1e12,
                                 "comparator": b.get("comparator_method"), "comp. F1": b.get("comparator_f1_macro"),
                                 "diff (pts)": 100 * b.get("mean_diff", float("nan")),
                                 "p (Bonf., max of t and W)": max(b.get("p_ttest_bonferroni", float("nan")),
                                                                  b.get("p_wilcoxon_bonferroni", float("nan"))),
                                 "verdict": b["verdict"],
                                 "PASS in family": int((prim[prim["condition"] == cond]["verdict"] == "PASS").sum())})
            per = prim[prim["operating_point"] == "b05"].copy()
            per["condition"] = per["condition"].map(cond_label)
            per["cell"] = [f"{v} ({100 * d:+.2f})" for v, d in zip(per["verdict"], per["mean_diff"])]
            pv = per.pivot_table(index="cheap", columns="condition", values="cell", aggfunc="first")
            pv = pv[[cond_label(c) for c in conds if cond_label(c) in pv.columns]]
            parts += ["### Every cheap pass at the 5% budget (b05): verdict and paired difference in points", "",
                      "Each cheap pass is its own system: n3g64, n4 and n4g128 escalate to the 8-bit parent they "
                      "are sliced from (one stored model); w3g64, w4 and w4g128 store two models.", "",
                      md(pv.reset_index()), ""]
            parts += ["### Primary cascades: the point with the largest paired difference at each rule", "",
                      "FP32 head, margin gate, W8 parent as the expensive target; the comparator is the best static "
                      "system (either head) with bit-ops no higher; Bonferroni over the 30 primary points of the "
                      "condition.", "", md(pd.DataFrame(rows), "{:.4g}"), ""]
        if comp is not None and len(comp):
            vc = comp.groupby(["family", "condition"])["verdict"].apply(lambda v: int((v == "PASS").sum()))
            vc = vc.unstack(0).reindex(conds).fillna(0).astype(int)
            vc.index = [cond_label(c) for c in vc.index]
            parts += ["### Number of points that PASS, per family (primary: 30 points; primaryread: the same points "
                      "with weight bits read as the cost)", "", md(vc.reset_index().rename(columns={"index": "condition"})),
                      ""]
            pr = comp[(comp["family"] == "primaryread") & (comp["verdict"] == "PASS")]
            if len(pr):
                t = pd.DataFrame({"condition": pr["condition"].map(cond_label), "cascade": pr["method"],
                                  "point": pr["operating_point"], "F1": pr["f1_macro"],
                                  "bits read (Mb)": pr["bitops_per_clip"] / 1e6, "comparator": pr["comparator_method"],
                                  "comp. F1": pr["comparator_f1_macro"], "diff (pts)": 100 * pr["mean_diff"]})
                parts += ["Points that PASS with bits read as the cost", "", md(t, "{:.4g}"), ""]
        hum = C[C["point"].isin(["clean_b10", "clean_b20"]) & (C["expensive"] != "fp32")]
        if len(hum):
            pv = hum.groupby(["point", "cheap", "condition"])["rate"].mean().unstack()
            pv = pv[sorted(pv.columns, key=cond_key)]
            pv.columns = [cond_label(c) for c in pv.columns]
            parts += ["### Humility curve: test escalation rate, thresholds set once on clean inner validation", "",
                      md(pv.reset_index()), ""]
            pf = hum.groupby(["point", "cheap", "condition"])["f1"].mean().unstack()
            pf = pf[sorted(pf.columns, key=cond_key)]
            pf.columns = [cond_label(c) for c in pf.columns]
            pb = hum.groupby(["point", "cheap", "condition"])["bitops"].mean().unstack() / 1e12
            pb = pb[sorted(pb.columns, key=cond_key)]
            pb.columns = [cond_label(c) for c in pb.columns]
            parts += ["F1 of the same clean-calibrated cascades", "", md(pf.reset_index()), "",
                      "Their bit-ops per clip (T)", "", md(pb.reset_index()), ""]
        if (adir / "auroc.csv").exists():
            A = pd.read_csv(adir / "auroc.csv")
            pv = A.groupby(["cheap", "condition"])["margin"].mean().unstack()
            pv = pv[sorted(pv.columns, key=cond_key)]
            pv.columns = [cond_label(c) for c in pv.columns]
            parts += ["### Margin AUROC for the cheap pass's errors that its W8 parent fixes (FP32 head, mean over "
                      "seeds)", "", md(pv.reset_index()), ""]
        cal = pd.read_csv(adir / "calibration.csv")
        cal = cal[(cal["head"].astype(str) == "esc") & cal["config"].isin(KEY_CONFIGS)]
        for val, title in (("ece", "ECE (15 bins)"), ("conf_gap", "mean confidence minus accuracy")):
            if val not in cal:
                continue
            pv = cal.pivot_table(index="config", columns="condition", values=val)
            pv = pv.reindex([c for c in KEY_CONFIGS if c in pv.index])[sorted(pv.columns, key=cond_key)]
            pv.columns = [cond_label(c) for c in pv.columns]
            parts += [f"### Calibration of static systems, FP32 head: {title}", "", md(pv.reset_index()), ""]
    args.out.write_text("\n".join(parts))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
